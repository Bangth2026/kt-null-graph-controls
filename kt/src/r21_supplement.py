"""Release 7.0.0: Online Resource 5 of the third UMUAI version (markdown), from the result files of results_r21."""
import os, json, glob, numpy as np, pandas as pd
from scipy.stats import norm
REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__))); R = f'{REPO}/results_r21'
J = lambda p: json.load(open(p))
Z = norm.ppf(0.975) + norm.ppf(0.80)
f4 = lambda x: ('---' if x is None else f'{x:+.4f}'.replace('-', '−'))
NAME = dict(assist09='ASSISTments 2009', assist12='ASSISTments 2012', assist15='ASSISTments 2015', assist17='ASSISTments 2017', junyi='Junyi Academy',
            algebra05='Algebra 2005', eedi='Eedi', ednet='EdNet KT1', bridge06='Bridge to Alg. 2006', statics11='Statics 2011', sim_dbe='sim-DBE', sim_a09='sim-A09')
TL = {'uni_emb-empty': 'U − ∅', 'true_er_emb-uni_emb': 'ER(G*) − U', 'true_dp_emb-true_er_emb': 'DP(G*) − ER(G*)', 'true_emb-true_dp_emb': 'G* − DP(G*)',
      'true_emb-empty': 'G* − ∅', 'er_emb-uni_emb': 'ER(G) − U', 'dp_emb-er_emb': 'DP(G) − ER(G)', 'support_emb-dp_emb': 'G − DP(G)',
      'support_emb-empty': 'G − ∅', 'true_emb-support_emb': 'G* − G'}


def table(df):
    cols = list(df.columns); L = ['| ' + ' | '.join(cols) + ' |', '|' + '|'.join(['---'] * len(cols)) + '|']
    L += ['| ' + ' | '.join(str(x) for x in r) + ' |' for r in df.itertuples(index=False)]
    return '\n'.join(L)


def main():
    L = ['---', 'title: "Online Resource 5"', '---', '',
         '**Do log-built concept graphs help KC-level learner models? Entry-point null graphs, a positive control and decision-level tests**', '',
         'Hai Bang Truong, Saigon International University. User Modeling and User-Adapted Interaction.', '',
         'Sections S17 to S22, added in the revision. Every value is produced by release 7.0.0 of the accompanying code (`kt/src/r21_*.py`) from the run files of `kt/runs_r21_sim`, `kt/runs_r21` and the earlier releases; the result files are `kt/results_r21/*.json`.', '']
    # S17
    PC = J(f'{R}/positive_control.json'); GR = J(f'{R}/graphs.json')
    L += ['# S17 Simulated worlds and the positive control', '',
          'Learners are generated by `kt/src/r20_sim.py` (world parameters `kt/graphs_r20/<world>_world.npz`, true graphs `<world>_true.json`); rebuilding the worlds reproduces the archived parameters exactly. The tracers are trained by `kt/src/r21_controls.py` under the update budget, graph in the embedding refinement. Terms on first attempts; mean over subsamples (0, 1, 2; subsample 0 at 100%), in parentheses units with a positive difference.', '']
    for w in ('sim_dbe', 'sim_a09'):
        rows = []
        for key, lab in TL.items():
            r = {'Term': lab}
            for f in ('5', '10', '25', '100'):
                v = PC['by_world'][w].get(f, {}).get(key); r[f'{f}%'] = '---' if v is None else f"{f4(v['mean'])} ({v['pos']}/{v['n']})"
            rows.append(r)
        L += [f'**Table S17.{1 if w == "sim_dbe" else 2}** {NAME[w]}: ladder on the true graph G* and on the log-built graph G', '', table(pd.DataFrame(rows)), '']
        rows = []
        for f in ('5', '10', '25', '100'):
            a = PC['by_world'][w].get(f, {}).get('auc', {})
            if a: rows.append({'Training learners': f'{f}%', **{c: f'{a[c]:.4f}' for c in ('empty', 'uni_emb', 'true_er_emb', 'true_dp_emb', 'true_emb', 'er_emb', 'dp_emb', 'support_emb') if c in a}})
        L += [f'First-attempt AUC by condition ({NAME[w]}):', '', table(pd.DataFrame(rows).fillna('---')), '']
    rows = []
    for w, res in GR['sim_recovery'].items():
        d = pd.DataFrame(res).groupby('frac').mean(numeric_only=True)
        for f, r in d.iterrows():
            rows.append({'World': NAME[w], 'Training learners': f'{int(f * 100)}%', 'Edges of G': f"{r.edges:.0f}", 'Edges of G*': f"{r.true_edges:.0f}",
                         'Recall of G*': f'{r.recall:.2f}', 'Precision': f'{r.precision:.2f}', 'Reversed edges of G*': f'{r.reversed:.2f}'})
    L += ['**Table S17.3** Recovery of the true graph by the support graph of Eq. (2) built from the simulated logs (mean over subsamples). Edges of G* counts the edges among KCs that occur in the logs.', '', table(pd.DataFrame(rows)), '']
    # S18
    rows = []
    for c, rs in GR['s_sensitivity'].items():
        d = pd.DataFrame(rs).groupby('s').mean(numeric_only=True)
        rows.append({'Corpus': NAME[c], **{f'Edges s={s}': f'{d.loc[s, "edges"]:.0f}' for s in (5, 10, 20)},
                     **{f'Precision s={s}': f'{d.loc[s, "precision"]:.2f}' for s in (5, 10, 20)}, **{f'Recall s={s}': f'{d.loc[s, "recall"]:.2f}' for s in (5, 10, 20)}})
    L += ['# S18 Sensitivity of the support graph to the threshold s of Eq. (2)', '',
          'At 10% of the training learners, mean over five subsamples; precision and recall against G~100~ built with s = 10 (`kt/src/r21_graphs.py`). A pair (a, b) is an edge exactly when T(a→b) + T(b→a) ≥ s and T(a→b) > T(b→a); the script checks this equivalence on every graph.', '',
          '**Table S18.1** Edges and agreement with G~100~ by s', '', table(pd.DataFrame(rows)), '']
    # S19
    SM = J(f'{R}/stats_more.json'); rows = []
    for k, v in SM['power'].items():
        rows.append({'Term': k.replace('r14/', '').replace('r16/', ''), 'Estimate': f4(v['est']), 'SE': f"{v['se']:.4f}", 'MDE (80%)': f"{v['mde80']:.4f}"})
    L += ['# S19 Power of every comparison', '', 'MDE = (z~0.975~ + z~0.80~) SE, from the standard error of the interval reported for the term (mixed model, or ordinary least squares with one unit per corpus); first attempts, 10% of the training learners, update budget (`kt/src/r21_stats.py`).', '',
          '**Table S19.1** Minimum detectable effect of the exploratory terms', '', table(pd.DataFrame(rows)), '']
    e = SM['ensembles']; rows = [{'Corpus': NAME[r['data']], 'Subsample': r['sub'], 'Graph gain, single seeds': f4(r['single_gain']), 'Graph gain, ensembles': f4(r['ens_gain']),
                                  'Ensemble − single, control': f4(r['ens_control_minus_single']), 'Ensemble − single, graph': f4(r['ens_graph_minus_single'])} for r in e['per_unit']]
    L += ['**Table S19.2** Seed ensembles on first-attempt AUC at 10% (three seeds per model; units with prediction files for all six runs)', '', table(pd.DataFrame(rows)), '']
    # S20
    DM = J(f'{R}/decisions_more.json')['per_corpus']; rows = []
    for c, d in DM.items():
        a = d['agreement_sets']
        rows.append({'Corpus': NAME[c], 'Seeds, target': f"{a['control_seeds']['target']:.3f}", 'Crossed, target': f"{a['graph_control_crossed']['target']:.3f}",
                     'Seeds, Jaccard 0.01': f"{a['control_seeds']['jaccard_near_0p01']:.3f}", 'Seeds, top-5': f"{a['control_seeds']['top5']:.3f}",
                     'Ensembles, target': f"{a['ensembles_graph_control']['target']:.3f}", 'Ensemble vs member': f"{a['ensemble_vs_member_control']['target']:.3f}"})
    L += ['# S20 Further decision analyses on the real corpora', '', '`kt/src/r21_decisions.py`; 25% of the training learners, subsample 0, seeds 0, 100, 200; candidate scores of release 5.0.0.', '',
          '**Table S20.1** Agreement by corpus', '', table(pd.DataFrame(rows)), '']
    tau = []
    for c, d in DM.items():
        for tv, v in d['tau'].items(): tau.append(dict(tau=float(tv), **v))
    t = pd.DataFrame(tau).groupby('tau').mean(numeric_only=True).reset_index()
