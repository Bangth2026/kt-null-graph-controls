def run_list():
    rows = []
    for d in ('runs_r21_sim', 'runs_r21', 'runs_r21/repro'):
        for f in sorted(glob.glob(f'{REPO}/kt/{d}/*__steps.json') + glob.glob(f'{REPO}/{d}/*__steps.json')):
            j = J(f); rows.append(dict(dir=d, data=j['data'], frac=j['frac'], sub=j['sub'], rep=j.get('rep', 0), seed=j['seed'], cond=j['cond'],
                                       steps=j['steps'], test_auc=j['test_auc'], test_auc_first=j['test_auc_first'], secs=round(j['secs_total'])))
    pd.DataFrame(rows).to_csv(f'{R}/run_list_r21.csv', index=False); print('runs', len(rows))


if __name__ == '__main__':
    main(); run_list()
